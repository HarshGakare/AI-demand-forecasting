from pathlib import Path
import pandas as pd



PROJECT_ROOT = Path(__file__).resolve().parents[1]
REPORT_DIR = PROJECT_ROOT / "reports"

OUTPUT_PATH = (REPORT_DIR/ "champion_model_evaluation.csv")
SUMMARY_PATH = (REPORT_DIR/ "champion_model_summary.csv")



def load_metric_files():
    """
    Load the evaluation reports generated by previous steps.
    """

    files = {
        "baseline": REPORT_DIR / "baseline_metrics.csv",
        "lightgbm": REPORT_DIR / "lightgbm_metrics.csv",
        "rolling_cv": REPORT_DIR / "rolling_cv_summary.csv",
        "recursive": REPORT_DIR / "recursive_forecast_metrics.csv",
        "ensemble": REPORT_DIR / "ensemble_final_metrics.csv",
        "multi_horizon": REPORT_DIR / "multi_horizon_metrics.csv",
    }

    results = {}

    for name, path in files.items():

        if path.exists():
            try:
                results[name] = pd.read_csv(path)
                print( f"Loaded {name}: {path.name}")

            except Exception as exc:
                print(
                    f"Could not load {name}: {exc}"
                )

        else:

            print(
                f"Skipping missing file: {path.name}"
            )

    return results




def extract_metric(df,metric_name):
    """
    Safely extract the first available value for a metric.
    """

    if df is None or df.empty:
        return None

    if metric_name not in df.columns:
        return None

    values = pd.to_numeric(df[metric_name],errors="coerce").dropna()

    if values.empty:
        return None

    return float(values.iloc[0])


def build_summary(results):
    """
    Build a consolidated model comparison table.
    """

    rows = []

    # Tuned LightGBM final holdout

    lightgbm = results.get("lightgbm")

    if lightgbm is not None:

        rows.append(
            {
                "Model": "Tuned LightGBM",
                "EvaluationType": "Final Holdout",
                "MAE": extract_metric(lightgbm,"MAE"),
                "RMSE": extract_metric(lightgbm,"RMSE"),
                "WAPE": extract_metric(lightgbm,"WAPE"),
                "Recommendation": "Candidate",
            }
        )

    # Rolling CV

    # --------------------------------------------------------
# Rolling CV
# --------------------------------------------------------

    rolling = results.get("rolling_cv")

    if rolling is not None and not rolling.empty:

        required_columns = { "Metric", "Mean" }

        if not required_columns.issubset(rolling.columns):
            raise ValueError(
                "rolling_cv_summary.csv must contain 'Metric' and 'Mean' columns."
            )

        rolling_lookup = ( rolling.set_index("Metric")["Mean"])

        required_metrics = {
            "MAE",
            "RMSE",
            "WAPE",
        }

        missing_metrics = (required_metrics- set(rolling_lookup.index))

        if missing_metrics:
            raise ValueError(
                "Missing rolling CV metrics: "
                + ", ".join(
                    sorted(missing_metrics)
                )
            )

        rows.append(
            {
                "Model": "Tuned LightGBM",
                "EvaluationType": "Rolling CV Mean",
                "MAE": float(
                    rolling_lookup["MAE"]
                ),
                "RMSE": float(
                    rolling_lookup["RMSE"]
                ),
                "WAPE": float(
                    rolling_lookup["WAPE"]
                ),
                "Recommendation": "Champion",
            }
        )

    # Recursive LightGBM

    recursive = results.get("recursive")

    if recursive is not None:

        recursive_30 = recursive.copy()

        if "Horizon" in recursive_30.columns:

            recursive_30["Horizon"] = pd.to_numeric(recursive_30["Horizon"],errors="coerce" )

            recursive_30 = recursive_30[recursive_30["Horizon"] == 30]

        rows.append(
            {
                "Model": "Recursive LightGBM",
                "EvaluationType": "30-Day Recursive",
                "MAE": extract_metric(recursive_30,"MAE"),
                "RMSE": extract_metric(recursive_30,"RMSE"),
                "WAPE": extract_metric(recursive_30,"WAPE"),
                "Recommendation": "Benchmark",
            }
        )

    # Ensemble

    ensemble = results.get("ensemble")

    if ensemble is not None:

        rows.append(
            {
                "Model": "LightGBM + ETS Ensemble",
                "EvaluationType": "Final Holdout",
                "MAE": extract_metric( ensemble,"MAE"),
                "RMSE": extract_metric( ensemble,"RMSE"),
                "WAPE": extract_metric( ensemble,"WAPE"),
                "Recommendation": "Rejected",
            }
        )

    # Baseline

    baseline = results.get("baseline")

    if baseline is not None:

        # Baseline file may contain one row per model.
        for _, row in baseline.iterrows():

            model_name = row.get("Model","Baseline" )

            rows.append(
                {
                    "Model": str(model_name),
                    "EvaluationType": "Baseline",
                    "MAE": pd.to_numeric( row.get("MAE"),errors="coerce"),
                    "RMSE": pd.to_numeric(row.get("RMSE"), errors="coerce"),
                    "WAPE": pd.to_numeric(row.get("WAPE"),errors="coerce"),
                    "Recommendation": "Benchmark",
                }
            )

    return pd.DataFrame(rows)



# ADD RANKINGS


def add_rankings(summary):
    """
    Rank models by WAPE, MAE and RMSE.
    Lower is better for all three metrics.
    """

    summary = summary.copy()

    summary["WAPERank"] = (
        summary["WAPE"].rank(method="min",ascending=True)
    )

    summary["MAERank"] = (
        summary["MAE"].rank(method="min",ascending=True)
    )

    summary["RMSERank"] = (
        summary["RMSE"].rank(method="min",ascending=True)
    )

    return summary



# CHAMPION DECISION

def create_champion_summary(summary):
    """
    Create the final model-selection decision.

    The rolling-CV LightGBM is treated as the production champion because it is evaluated across multiple chronological validation windows.
    """

    champion_rows = summary[
        (summary["Model"] == "Tuned LightGBM")
        &
        ( summary["EvaluationType"] == "Rolling CV Mean")
    ]

    if champion_rows.empty:
        raise ValueError("Rolling CV LightGBM result was not found." )

    champion = champion_rows.iloc[0]

    result = pd.DataFrame(
        [
            {
                "ChampionModel": ( "Tuned LightGBM"),
                "SelectionBasis": (
                    "Rolling chronological "
                    "cross-validation"
                ),
                "MeanMAE": champion["MAE"],
                "MeanRMSE": champion["RMSE"],
                "MeanWAPE": champion["WAPE"],
                "FinalDecision": (
                    "Use tuned LightGBM as forecasting champion"
                ),
                "RecursiveForecastStatus": (
                    "Benchmark only; recursive "
                    "error propagation materially "
                    "reduced accuracy"
                ),
                "EnsembleStatus": (
                    "Rejected; ETS ensemble did not improve final holdout performance"
                ),
            }
        ]
    )

    return result


